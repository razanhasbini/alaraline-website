"""Build the site's pages from src/.

Every page shares the same head, header, mobile menu, footer, shopping bag and search
(src/partials/top.html and bottom.html); each page's own content lives in src/pages/<file>.html,
headed by a meta block:

    <!--meta
    title: Shop - ÀLara Line
    desc: One line for search engines.
    nav: shop                      (marks the matching header link as current)
    body: page-shop                (class on <body>)
    head: <link rel="preload" ...> (optional, extra lines in <head>)
    css: assets/css/banners.css    (optional, comma-separated, after the shared styles)
    js: assets/js/main.js, ...     (in order, after the shared data scripts)
    -->

Run from the project root:  python3 tools/build_pages.py
The pages it writes (index.html, shop.html, ...) are generated: edit src/, then rebuild.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'src'
TOP = (SRC / 'partials' / 'top.html').read_text()
BOTTOM = (SRC / 'partials' / 'bottom.html').read_text()
BANNER = '<!-- Generated by tools/build_pages.py from src/pages/{name}. Edit the source, then rebuild. -->\n'


def parse(text):
    m = re.match(r'<!--meta\n(.*?)\n-->\n', text, re.S)
    if not m:
        raise SystemExit('missing <!--meta ... --> block')
    meta = {}
    for line in m.group(1).splitlines():
        if ':' in line:
            k, v = line.split(':', 1)
            meta[k.strip()] = v.strip()
    return meta, text[m.end():]


def build(path):
    meta, body = parse(path.read_text())
    css = ''.join(f'  <link rel="stylesheet" href="{c.strip()}">\n' for c in meta.get('css', '').split(',') if c.strip())
    js = ''
    for s in meta.get('js', '').split(','):
        s = s.strip()
        if not s:
            continue
        module = s.startswith('module ')
        js += f'  <script{" type=\"module\"" if module else ""} src="{s.removeprefix("module ")}"></script>\n'
    head = meta.get('head', '')
    page = (TOP.replace('{{TITLE}}', meta['title']).replace('{{DESC}}', meta.get('desc', ''))
            .replace('{{HEAD}}', f'  {head}\n' if head else '').replace('{{CSS}}', css)
            .replace('{{BODY}}', meta.get('body', '')))
    nav = meta.get('nav')
    if nav:   # mark the current page in the header and the mobile menu
        page = page.replace(f'data-nav="{nav}"', f'data-nav="{nav}" class="is-current" aria-current="page"')
        page = page.replace(f'class="nav-lab" data-nav="{nav}" class="is-current"', f'class="nav-lab is-current" data-nav="{nav}"')
    page += body.rstrip('\n') + '\n' + BOTTOM.replace('{{EXTRA}}', '').replace('{{JS}}', js)
    page = page.replace('<html lang="en" data-season="christmas">', BANNER.format(name=path.name) + '<html lang="en" data-season="christmas">', 1)
    (ROOT / path.name).write_text(page)
    return path.name


if __name__ == '__main__':
    for p in sorted((SRC / 'pages').glob('*.html')):
        print('built', build(p))
